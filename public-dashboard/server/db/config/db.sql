-- Table for the microwaves
CREATE TABLE microwaves (
    id CHAR(36) PRIMARY KEY DEFAULT (UUID()),
    name VARCHAR(255) NOT NULL,
    description TEXT,
    createdAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Table for queue snapshots
CREATE TABLE queue_snapshots (
    id CHAR(36) PRIMARY KEY DEFAULT (UUID()),
    microwaveId CHAR(36) NOT NULL,
    queueCount INT NOT NULL,
    measuredAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (microwaveId) REFERENCES microwaves(id) ON DELETE CASCADE,
    INDEX idx_microwave_measured_at (microwaveId, measuredAt)
);

